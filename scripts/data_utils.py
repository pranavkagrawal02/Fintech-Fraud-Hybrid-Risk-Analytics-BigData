def write_jsonl_gz(df, path):
    """Write one nested JSON document per line (gzip)."""
    n = 0
    with gzip.open(path, "wt", encoding="utf-8") as f:
        for r in df.itertuples(index=False):
            tags = []
            if r.amount > 200000:
                tags.append("high_value")
            if r.tx_country != r.home_country:
                tags.append("foreign")
            if int(r.ts_str[11:13]) < 6:
                tags.append("night")
            doc = {
                "tx_id": r.tx_id,
                "step": int(r.step),
                "ts": r.ts_str,
                "type": r.type,
                "amount": round(float(r.amount), 2),
                "origin": {
                    "account": r.nameOrig,
                    "old_balance": float(r.oldbalanceOrg),
                    "new_balance": float(r.newbalanceOrig),
                    "home_city": r.home_city, "home_country": r.home_country,
                    "home_lat": float(r.home_lat), "home_lon": float(r.home_lon),
                },
                "dest": {
                    "account": r.nameDest,
                    "old_balance": float(r.oldbalanceDest),
                    "new_balance": float(r.newbalanceDest),
                    "is_merchant": bool(str(r.nameDest).startswith("M")),
                },
                "merchant_category": r.merchant_category,
                "device": {"id": r.device_id, "os": r.device_os},
                "city": r.tx_city,
                "country": r.tx_country,
                "location": {"type": "Point", "coordinates": [float(r.tx_lon), float(r.tx_lat)]},
                "tags": tags,
                "is_fraud": int(r.isFraud),
                "is_flagged_fraud": int(r.isFlaggedFraud),
            }
            f.write(json.dumps(doc) + "\n")
            n += 1
    return n
