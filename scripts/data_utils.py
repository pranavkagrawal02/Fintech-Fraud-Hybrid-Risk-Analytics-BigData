"""
data_utils.py - helpers used by 02_prepare_sample_and_enrich.py

 * make_synthetic_paysim()  : builds a PaySim-like DataFrame (fallback if you cannot download Kaggle data)
 * enrich_df()              : adds SYNTHETIC enrichment fields (device, geo, merchant category, timestamp)
 * write_jsonl_gz()         : writes nested JSON documents (one per line, gzip) ready for MongoDB

IMPORTANT (say this in your report): device / geo / merchant_category / timestamp are SYNTHETIC
enrichment fields generated by this script. Fraud rows are given a higher chance of using shared
"ring" devices and of appearing in a city different from the account's home city.
"""
import gzip
import json

import numpy as np
import pandas as pd

# (city, country, lat, lon)
CITIES = [
    ("Mumbai", "IN", 19.0760, 72.8777), ("Delhi", "IN", 28.7041, 77.1025),
    ("Bengaluru", "IN", 12.9716, 77.5946), ("Chennai", "IN", 13.0827, 80.2707),
    ("Kolkata", "IN", 22.5726, 88.3639), ("Dubai", "AE", 25.2048, 55.2708),
    ("Singapore", "SG", 1.3521, 103.8198), ("London", "GB", 51.5074, -0.1278),
    ("New York", "US", 40.7128, -74.0060), ("Lagos", "NG", 6.5244, 3.3792),
    ("Nairobi", "KE", -1.2864, 36.8172), ("Sao Paulo", "BR", -23.5505, -46.6333),
]
MERCHANT_CATS = ["grocery", "electronics", "travel", "restaurants", "fuel", "fashion",
                 "entertainment", "utilities"]
OS_LIST = ["android", "ios", "web"]
RING_DEVICES = [f"DR{i:04d}" for i in range(1, 61)]  # shared devices used by fraud rings


# --------------------------------------------------------------------------------------
def make_synthetic_paysim(n=300000, seed=42):
    """PaySim-like data with the same columns as the Kaggle CSV (used only if no download)."""
    rng = np.random.default_rng(seed)
    types = rng.choice(["PAYMENT", "CASH_OUT", "CASH_IN", "TRANSFER", "DEBIT"], n,
                       p=[0.34, 0.35, 0.22, 0.084, 0.006])
    step = rng.integers(1, 744, n)
    amount = np.round(rng.lognormal(9.5, 1.3, n), 2)
    fraud = ((types == "TRANSFER") | (types == "CASH_OUT")) & (rng.random(n) < 0.04)
    amount = np.where(fraud, np.round(rng.lognormal(12.0, 1.0, n), 2), amount)

    name_orig = np.char.add("C", rng.integers(10**8, 10**9, n).astype(str))
    dest_c = np.char.add("C", rng.integers(10**8, 10**9, n).astype(str))
    dest_m = np.char.add("M", rng.integers(10**8, 10**9, n).astype(str))
    name_dest = np.where(types == "PAYMENT", dest_m, dest_c)

    old_org = np.round(rng.lognormal(10.5, 1.5, n), 2)
    old_org = np.where(fraud, amount, np.maximum(old_org, np.where(types == "CASH_IN", 0, amount)))
    new_org = np.where(types == "CASH_IN", old_org + amount, np.maximum(old_org - amount, 0))
    is_merchant = types == "PAYMENT"
    old_dest = np.where(is_merchant, 0.0, np.round(rng.lognormal(10.0, 1.6, n), 2))
    new_dest = np.where(is_merchant, 0.0, old_dest + amount)

    df = pd.DataFrame({
        "step": step, "type": types, "amount": amount, "nameOrig": name_orig,
        "oldbalanceOrg": old_org, "newbalanceOrig": new_org, "nameDest": name_dest,
        "oldbalanceDest": old_dest, "newbalanceDest": new_dest, "isFraud": fraud.astype(int),
        "isFlaggedFraud": ((types == "TRANSFER") & (amount > 200000)).astype(int),
    })

    # fraud pattern from PaySim: TRANSFER to account X, then X cashes out -> creates chains
    # (used later by $graphLookup)
    t = df[(df.isFraud == 1) & (df.type == "TRANSFER")]
    t = t.sample(frac=0.5, random_state=seed)
    comp = pd.DataFrame({
        "step": t["step"].values, "type": "CASH_OUT", "amount": t["amount"].values,
        "nameOrig": t["nameDest"].values,
        "oldbalanceOrg": t["amount"].values, "newbalanceOrig": 0.0,
        "nameDest": np.char.add("C", rng.integers(10**8, 10**9, len(t)).astype(str)),
        "oldbalanceDest": 0.0, "newbalanceDest": t["amount"].values,
        "isFraud": 1, "isFlaggedFraud": 0,
    })
    return pd.concat([df, comp], ignore_index=True)


# --------------------------------------------------------------------------------------
def enrich_df(df, seed=42):
    """Add synthetic enrichment columns. Returns a new DataFrame sorted by step."""
    rng = np.random.default_rng(seed)
    df = df.sort_values("step", kind="mergesort").reset_index(drop=True)
    n = len(df)
    nc = len(CITIES)
    fraud = df["isFraud"].to_numpy().astype(int)

    # deterministic "home city" per origin account
    h = pd.util.hash_pandas_object(df["nameOrig"].astype(str), index=False).to_numpy()
    home_idx = (h % nc).astype(int)

    # where the transaction actually happened (fraud travels far more often)
    travel = rng.random(n) < np.where(fraud == 1, 0.55, 0.03)
    other_idx = (home_idx + rng.integers(1, nc, n)) % nc
    tx_idx = np.where(travel, other_idx, home_idx)

    lat = np.array([c[2] for c in CITIES])
    lon = np.array([c[3] for c in CITIES])
    cty = np.array([c[0] for c in CITIES])
    cc = np.array([c[1] for c in CITIES])
    df["home_city"], df["home_country"] = cty[home_idx], cc[home_idx]
    df["home_lat"], df["home_lon"] = lat[home_idx], lon[home_idx]
    df["tx_city"], df["tx_country"] = cty[tx_idx], cc[tx_idx]
    df["tx_lat"] = np.round(lat[tx_idx] + rng.normal(0, 0.05, n), 5)
    df["tx_lon"] = np.round(lon[tx_idx] + rng.normal(0, 0.05, n), 5)

    # devices: normal traffic = pseudo-random device pool (some sharing); 60% of fraud = ring devices
    dev = np.char.add("D", (h % 400000).astype(str))
    ring = (fraud == 1) & (rng.random(n) < 0.6)
    df["device_id"] = np.where(ring, rng.choice(RING_DEVICES, n), dev)
    df["device_os"] = rng.choice(OS_LIST, n, p=[0.55, 0.30, 0.15])

    # merchant category
    t = df["type"].to_numpy()
    df["merchant_category"] = np.where(
        t == "PAYMENT", rng.choice(MERCHANT_CATS, n),
        np.where(t == "TRANSFER", "p2p_transfer", np.where(t == "DEBIT", "bank_debit", "cash_agent")))

    # timestamp: step = hour since 2026-01-01
    ts = (pd.Timestamp("2026-01-01") + pd.to_timedelta(df["step"].to_numpy(), unit="h")
          + pd.to_timedelta(rng.integers(0, 3600, n), unit="s"))
    df["ts_str"] = ts.strftime("%Y-%m-%dT%H:%M:%S").to_numpy()
    df["tx_id"] = ["TX" + str(i).zfill(8) for i in range(n)]
    return df


